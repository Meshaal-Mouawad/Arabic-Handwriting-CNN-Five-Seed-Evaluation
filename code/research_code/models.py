from __future__ import annotations

import torch
from torch import nn
from torch.nn import functional as F


def cnn_encoder() -> nn.Module:
    """CNN matching the archived Conv(activation)->BN->pool->dropout order."""
    blocks = []
    channels = 1
    for filters in (16, 32, 64, 128):
        blocks.extend([
            nn.Conv2d(channels, filters, kernel_size=3, padding=1, bias=True),
            nn.ReLU(inplace=False),
            nn.BatchNorm2d(filters, eps=1e-3, momentum=0.01),
            nn.MaxPool2d(kernel_size=2),
            nn.Dropout(p=0.2),
        ])
        channels = filters
    blocks.extend([nn.AdaptiveAvgPool2d(1), nn.Flatten()])
    return nn.Sequential(*blocks)


class FlatCNN(nn.Module):
    """38-way pooled CNN. Equivalent layer-level topology to archived baseline."""
    def __init__(self):
        super().__init__()
        self.encoder = cnn_encoder()
        self.head = nn.Linear(128, 38)

    def forward(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        logp = F.log_softmax(self.head(self.encoder(x)), dim=-1)
        family_logp = torch.stack([
            torch.logsumexp(logp[:, :10], dim=1),
            torch.logsumexp(logp[:, 10:], dim=1),
        ], dim=1)
        return logp, family_logp


class HierarchicalCNN(nn.Module):
    """Shared convolutional encoder with a 2-way gate and 10/28 specialist heads.

    Concatenation order is digit labels 0--9 then letter labels 10--37.
    The joint distribution is normalized by construction.
    """
    def __init__(self):
        super().__init__()
        self.encoder = cnn_encoder()
        self.family_head = nn.Linear(128, 2)
        self.digit_head = nn.Linear(128, 10)
        self.letter_head = nn.Linear(128, 28)

    def forward(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        z = self.encoder(x)
        family_logp = F.log_softmax(self.family_head(z), dim=-1)
        digit = family_logp[:, 0:1] + F.log_softmax(self.digit_head(z), dim=-1)
        letter = family_logp[:, 1:2] + F.log_softmax(self.letter_head(z), dim=-1)
        return torch.cat([digit, letter], dim=1), family_logp


class CapacityMatchedFlatCNN(nn.Module):
    """Sensitivity control: flat classifier with an ACTIVE, redundant 2-group offset.

    This has exactly the same trainable parameter count as HierarchicalCNN.
    Its softmax decision class is identical to an unconstrained flat affine head:
    adding the same learned affine offset to all logits in a family can be
    absorbed into the per-class affine weights. Thus it controls training
    dynamics from two extra outputs without adding hierarchical factorization.
    """
    def __init__(self):
        super().__init__()
        self.encoder = cnn_encoder()
        self.head = nn.Linear(128,38)
        self.group_offsets = nn.Linear(128,2)
        nn.init.zeros_(self.group_offsets.weight)
        nn.init.zeros_(self.group_offsets.bias)

    def forward(self, x:torch.Tensor) -> tuple[torch.Tensor,torch.Tensor]:
        z=self.encoder(x)
        offset=self.group_offsets(z)
        grouped=torch.cat((
            offset[:,0:1].expand(-1,10),
            offset[:,1:2].expand(-1,28)),dim=1)
        logp=F.log_softmax(self.head(z)+grouped,dim=1)
        fl=torch.stack((torch.logsumexp(logp[:,:10],dim=1),
                        torch.logsumexp(logp[:,10:],dim=1)),dim=1)
        return logp,fl


def family_risk(logp: torch.Tensor, labels: torch.Tensor,
                rule: str = "ce", lam: float = 0.5,
                tau: float = 0.2) -> tuple[torch.Tensor, dict]:
    """Compare sample risk with family average and soft worst-family risk.

    A 'balanced' or 'smooth_worst' minibatch MUST contain examples of
    both symbol families. All experiments must use the same batch schedule.
    """
    if labels.ndim != 1 or logp.shape[1] != 38:
        raise ValueError("Expected integer targets and 38-class log probabilities")
    if rule not in {"ce", "balanced", "smooth_worst"}:
        raise ValueError("rule must be 'ce', 'balanced', or 'smooth_worst'")
    nll = F.nll_loss(logp, labels, reduction="none")
    digit = labels < 10
    letter = ~digit
    if rule == "ce":
        return nll.mean(), {"mean_nll": float(nll.detach().mean())}
    if not bool(digit.any()) or not bool(letter.any()):
        raise ValueError("Family-aware losses require a batch containing both families")
    ld = nll[digit].mean()
    ll = nll[letter].mean()
    mean = (ld + ll) / 2
    if rule == "balanced":
        loss = mean
    else:
        if not 0 <= lam <= 1 or tau <= 0:
            raise ValueError("lambda must be in [0,1] and tau must be positive")
        # -log(2) normalizes the smooth maximum to equal group loss when ld=ll.
        smooth = tau * (torch.logsumexp(torch.stack((ld, ll))/tau, dim=0)
                        - torch.log(torch.tensor(2., device=ld.device)))
        loss = (1-lam) * mean + lam * smooth
    return loss, {"digit_nll": float(ld.detach()), "letter_nll": float(ll.detach())}


