"""Paired comparison of exact saved 38-class predictions.

Inputs are ONLY generated by `benchmark.py evaluate` after model selection.
Samples are paired between models and corruption settings. Report image-level
stratified-bootstrap CIs separately from run-seed interval; avoid p-hacking.
"""
from __future__ import annotations
import argparse,json
from pathlib import Path
from math import sqrt
import numpy as np
from scipy.stats import t as student_t

SEEDS=(7,17,29,43,61)
CONDS=['none_0.0','noise_0.05','noise_0.1','blur_0.8','blur_1.3','contrast_0.75','contrast_0.5']
CONTRASTS={
 'H1_flat_balance':('B1_flat_balanced','B0_flat_ce'),
 'H2_hierarchy_CE':('B2_hier_ce','B0_flat_ce'),
 'H2_hierarchy_balanced':('B3_hier_balanced','B1_flat_balanced'),
 'H3_smooth_worst':('P_hier_smooth_worst','B3_hier_balanced'),
 'capacity_H2_vs_matched_flat':('B2_hier_ce','C_flat_matched')}


def worst_macro_f1(y,pred):
    conf=np.bincount(y.astype(np.int64)*38+pred.astype(np.int64),minlength=38*38).reshape(38,38)
    tp=np.diag(conf).astype(float)
    row=conf.sum(1).astype(float)
    col=conf.sum(0).astype(float)
    d=2*tp+row+col-2*tp
    f1=np.divide(2*tp,d,out=np.zeros_like(tp),where=d>0)
    return float(min(f1[:10].mean(),f1[10:].mean()))


def stratified_indices(y,rng,writer_groups=None):
    if writer_groups is None:
        return np.concatenate([rng.choice(v,size=len(v),replace=True)
                               for z in range(38) if len(v:=np.flatnonzero(y==z))])
    # Writer-cluster bootstrap separately within each family, using whole clusters.
    # Assumes source-disjoint writer IDs were verified before supplying them.
    indices=[]
    for mask in (y<10,y>=10):
        sub=np.flatnonzero(mask)
        unique=np.unique(writer_groups[sub])
        draw=rng.choice(unique,size=len(unique),replace=True)
        for writer in draw:
            indices.extend(sub[writer_groups[sub]==writer].tolist())
    return np.asarray(indices,dtype=np.int64)


def paired_effect(a,b,y,condition,baseline='none_0.0',subset=None):
    pos=np.arange(len(y)) if subset is None else subset
    y0=y[pos]
    e=worst_macro_f1(y0,a[f'pred_{condition}'][pos])-worst_macro_f1(y0,b[f'pred_{condition}'][pos])
    if condition==baseline:return e
    # Positive retention: method a loses less from clean to corruption than b.
    a_drop=worst_macro_f1(y0,a[f'pred_{condition}'][pos])-worst_macro_f1(y0,a[f'pred_{baseline}'][pos])
    b_drop=worst_macro_f1(y0,b[f'pred_{condition}'][pos])-worst_macro_f1(y0,b[f'pred_{baseline}'][pos])
    return e,a_drop-b_drop


def seed_interval(values):
    vals=np.array(values,dtype=float)
    if len(vals)<2:return {'mean':float(vals.mean()),'sd':None,'ci_95':None,'n_seeds':len(vals)}
    mean=float(vals.mean());sd=float(vals.std(ddof=1))
    delta=float(student_t.ppf(.975,len(vals)-1))*sd/sqrt(len(vals))
    return {'mean':mean,'sd':sd,'ci_95':[mean-delta,mean+delta], 'n_seeds':len(vals),
            'per_seed_differences':vals.tolist(),
            'interpretation':'Student-t descriptive interval over 5 paired training seeds; not a preregistered significance test'}


def run(root,seed_list,boots):
    root=Path(root)
    data={}
    for name in set(x for pair in CONTRASTS.values() for x in pair):
        for seed in seed_list:
            fp=root/f'{name}_seed{seed}'/'predictions.npz'
            if not fp.exists():raise FileNotFoundError(f'Missing {fp} (do not substitute synthetic predictions)')
            with np.load(fp,allow_pickle=False) as f:
                data[name,seed]={k:f[k] for k in f.files}
    result={'evaluation_label':'HELD-OUT TEST STATISTICS; run only after complete real-image evaluation',
            'seeds':list(seed_list),'bootstrap_replicates':boots,'contrasts':{},
            'bootstrap_design':'stratified with replacement independently within each of 38 ground-truth labels, paired between model predictions',
            'seed_interval_design':'Student-t on model-paired results from independent training seeds; results from data bootstrap reported separately'}
    for key,(new,base) in CONTRASTS.items():
        rows=[];all_seed_effects={c:[] for c in CONDS}
        all_seed_retention={c:[] for c in CONDS[1:]}
        for seed in seed_list:
            a=data[new,seed];b=data[base,seed]
            if set(a)!=set(b):raise ValueError(f'Mismatched prediction array keys for {key}, seed={seed}')
            y=a['y_true']
            if not np.array_equal(y,b['y_true']):raise ValueError('Predictions not evaluated on identical ordered samples')
            for c in CONDS:
                effect=paired_effect(a,b,y,c)
                val=effect if c=='none_0.0' else effect[0]
                all_seed_effects[c].append(float(val))
                if c!='none_0.0':all_seed_retention[c].append(float(effect[1]))
            if seed==seed_list[0] and boots>0:
                rng=np.random.default_rng(2291)
                samples={c:[] for c in CONDS}
                ret={c:[] for c in CONDS[1:]}
                writer_groups=a.get('writer_groups')
                if writer_groups is not None and not np.array_equal(writer_groups,b.get('writer_groups')):
                    raise ValueError('Writer-group manifests differ between paired models')
                for _ in range(boots):
                    idx=stratified_indices(y,rng,writer_groups)
                    for c in CONDS:
                        e=paired_effect(a,b,y,c,subset=idx)
                        samples[c].append(float(e if c=='none_0.0' else e[0]))
                        if c!='none_0.0':ret[c].append(float(e[1]))
                boot_data={'seed':seed,
                    'paired_image_level_CI':{c:list(map(float,np.quantile(v,[.025,.975]))) for c,v in samples.items()},
                    'paired_retention_CI':{c:list(map(float,np.quantile(v,[.025,.975]))) for c,v in ret.items()},
                    'resampling_unit':'writer clusters' if writer_groups is not None else 'images stratified by true class',
                    'warning':'Image bootstrap ignores within-writer dependence when writer IDs are unavailable' if writer_groups is None else 'Cluster bootstrap uses whole writer groups within each family'}
        clean=seed_interval(all_seed_effects['none_0.0'])
        effects={c:seed_interval(v) for c,v in all_seed_effects.items()}
        retention={c:seed_interval(v) for c,v in all_seed_retention.items()}
        if key=='H3_smooth_worst':
            mean_retention_by_seed=np.mean(np.stack([all_seed_retention[c] for c in CONDS[1:]]),axis=0)
            retention['H3_prespecified_mean_across_6_corruptions']=seed_interval(mean_retention_by_seed.tolist())
        result['contrasts'][key]={'method':new,'control':base,'clean_worst_family_F1_difference':clean,
                         'condition_F1_differences':effects,'retention_differences':retention,
                         'bootstrap_first_seed_only':boot_data if boots>0 else None}
    return result


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--runs',required=True)
    p.add_argument('--seeds',type=int,nargs='+',default=list(SEEDS))
    p.add_argument('--bootstrap',type=int,default=500)
    p.add_argument('--out',required=True)
    a=p.parse_args()
    out=run(a.runs,a.seeds,a.bootstrap)
    Path(a.out).write_text(json.dumps(out,indent=2))
    print(f'PASS: paired 38-class, six-corruption comparisons summarized in {a.out}')
if __name__=='__main__':main()
